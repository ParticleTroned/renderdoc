"""Derive independent fork releases without changing RenderDoc's upstream version."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET


TAG = re.compile(r"pt-v(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)")
SUBJECT = re.compile(r"^(feat|fix|perf|revert|build|ci|docs|test|refactor|style|chore)(?:\([^\n)]+\))?(!)?: (.+)")
GENERATED = "<!-- Generated by util/fork_version.py; do not edit. -->"


def git(repository, *arguments, required=True):
    result = subprocess.run(
        ["git", "-C", str(repository), *arguments],
        text=True, encoding="utf-8", stdout=subprocess.PIPE, stderr=subprocess.PIPE,
    )
    if required and result.returncode:
        raise ValueError(result.stderr.strip() or "Git command failed")
    return result.stdout.strip() if result.returncode == 0 else None


def upstream_version(repository):
    source = (repository / "renderdoc/api/replay/version.h").read_text(encoding="utf-8")
    components = []
    for name in ("MAJOR", "MINOR"):
        values = re.findall(r"^#define RENDERDOC_VERSION_" + name + r" ([0-9]+)$", source, re.M)
        if len(values) != 1:
            raise ValueError("Expected one upstream RENDERDOC_VERSION_" + name)
        components.append(str(int(values[0])))
    return ".".join(components)


def release_tag(repository):
    tag = git(repository, "describe", "--tags", "--first-parent", "--abbrev=0",
              "--match=pt-v[0-9]*", "HEAD", required=False)
    if tag and not TAG.fullmatch(tag):
        raise ValueError("Invalid fork release tag: " + tag)
    return tag


def metadata(repository, allow_unreleased=False, expected_tag=None, distribution="ParticleTroned/renderdoc"):
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", distribution):
        raise ValueError("Distribution must be a GitHub owner/repository")
    source = git(repository, "rev-parse", "HEAD")
    upstream = upstream_version(repository)
    tag = release_tag(repository)
    dirty = bool(git(repository, "status", "--porcelain", "--untracked-files=no"))
    if tag:
        fork = tag.removeprefix("pt-v")
        distance = int(git(repository, "rev-list", "--first-parent", "--count", tag + "..HEAD"))
        suffix = ".dev." + str(distance) + "." + source[:12] if distance else ""
    else:
        if not allow_unreleased or git(repository, "tag", "--list", "pt-v*"):
            raise ValueError("No reachable pt-vX.Y.Z release; fetch tags and full history")
        fork, suffix = "0.0.0", ".dev." + source[:12]
    if expected_tag and (tag != expected_tag or suffix or dirty):
        raise ValueError("Release build must use the exact clean fork tag: " + expected_tag)
    if dirty:
        suffix += ".dirty"
    return {"upstream": upstream, "fork": fork, "version": upstream + "+pt." + fork + suffix,
            "source": source, "tag": tag or "", "distribution": distribution,
            "contact": "https://github.com/" + distribution + "/issues"}


def write_props(path, identity):
    if path.exists() and GENERATED not in path.read_text(encoding="utf-8"):
        raise ValueError("Refusing to replace an unmanaged MSBuild props file")
    project = ET.Element("Project", xmlns="http://schemas.microsoft.com/developer/msbuild/2003")
    definitions = ET.SubElement(project, "ItemDefinitionGroup")
    values = ';'.join('DISTRIBUTION_' + key + '="' + identity[value] + '"'
                      for key, value in (("NAME", "distribution"), ("VERSION", "version"),
                                         ("CONTACT", "contact")))
    for tool in ("ClCompile", "ResourceCompile"):
        ET.SubElement(ET.SubElement(definitions, tool), "PreprocessorDefinitions").text = (
            values + ";%(PreprocessorDefinitions)")
    content = '<?xml version="1.0" encoding="utf-8"?>\n' + GENERATED + "\n" + ET.tostring(project, encoding="unicode") + "\n"
    if not path.exists() or path.read_text(encoding="utf-8") != content:
        path.write_text(content, encoding="utf-8")


def next_release(repository, bump="auto"):
    previous = release_tag(repository)
    source = git(repository, "rev-parse", "HEAD")
    if previous and git(repository, "rev-parse", previous + "^{commit}") == source:
        return {"released": False}
    base = previous or git(repository, "rev-parse", "HEAD^", required=False)
    revision = base + "..HEAD" if base else "HEAD"
    messages = git(repository, "log", "--no-merges", "--format=%B%x00", revision).split("\0")
    level = {"auto": 0, "patch": 1, "minor": 2, "major": 3}[bump]
    # The first release establishes the namespace even if several PRs merge before checkout.
    if not previous:
        level = max(level, 1)
    changes = []
    for message in messages:
        message = message.strip()
        subject = message.splitlines()[0] if message else ""
        match = SUBJECT.fullmatch(subject)
        if not match or subject.startswith("chore(upstream-sync):"):
            continue
        kind, breaking, description = match.groups()
        if breaking or re.search(r"^BREAKING[ -]CHANGE: .+", message, re.M):
            level = 3
        elif kind == "feat":
            level = max(level, 2)
        elif kind in ("fix", "perf", "revert"):
            level = max(level, 1)
        changes.append(subject)
    if not level:
        return {"released": False}
    if previous:
        version = [int(value) for value in TAG.fullmatch(previous).groups()]
        index = 3 - level
        version[index] += 1
        version[index + 1:] = [0] * (2 - index)
    else:
        version = [1, 0, 0]
    fork = ".".join(str(value) for value in version)
    upstream = upstream_version(repository)
    if git(repository, "rev-parse", "--verify", "refs/tags/pt-v" + fork, required=False):
        raise ValueError("Fork release tag already exists outside the selected release history")
    return {"released": True, "tag": "pt-v" + fork, "fork": fork, "upstream": upstream,
            "version": upstream + "+pt." + fork, "source": source,
            "changes": list(dict.fromkeys(changes))}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("metadata", "release"))
    parser.add_argument("--repository", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--allow-unreleased", action="store_true")
    parser.add_argument("--expect-tag")
    parser.add_argument("--distribution", default="ParticleTroned/renderdoc")
    parser.add_argument("--msbuild-props", type=Path)
    parser.add_argument("--bump", choices=("auto", "patch", "minor", "major"), default="auto")
    parser.add_argument("--github-output", type=Path)
    parser.add_argument("--notes", type=Path)
    args = parser.parse_args()
    try:
        if args.command == "metadata":
            result = metadata(args.repository, args.allow_unreleased, args.expect_tag, args.distribution)
            if args.msbuild_props:
                write_props(args.msbuild_props, result)
        else:
            result = next_release(args.repository, args.bump)
            if args.notes and result["released"]:
                notes = ("Fork release **" + result["tag"] + "**, based on upstream RenderDoc **" +
                         result["upstream"] + "**.\n\nRuntime version: `" + result["version"] + "`.\n\n")
                notes += "\n".join("- " + subject for subject in result["changes"]) + "\n"
                args.notes.write_text(notes, encoding="utf-8")
        if args.github_output:
            with args.github_output.open("a", encoding="utf-8") as output:
                for key, value in result.items():
                    if not isinstance(value, list):
                        output.write(key + "=" + (str(value).lower() if isinstance(value, bool) else value) + "\n")
        print(json.dumps(result, sort_keys=True))
        return 0
    except (OSError, ValueError) as error:
        print(str(error), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
